# Bab 04: Operator

# Operator aritmatika
a = 7
b = 3
print("Penjumlahan:", a + b)
print("Pengurangan:", a - b)
print("Perkalian:", a * b)
print("Pembagian:", a / b)
print("Pembagian bulat:", a // b)
print("Sisa bagi:", a % b)
print("Pangkat:", a ** b)
print("Urutan operasi 2 + 3 * 4 ** 2 =", 2 + 3 * 4 ** 2)

# Operator perbandingan dan logika
umur = 20
punya_ktp = True
print(umur >= 17 and punya_ktp)
print(umur < 13 or umur > 60)
print(not punya_ktp)

# Operator penugasan
skor = 10
skor += 5
skor *= 2
print("Skor:", skor)

# Operator keanggotaan
buah = ["apel", "jeruk", "mangga"]
print("apel" in buah)
print("anggur" not in buah)
print("th" in "Python")
